def main():
    script_dir = Path(__file__).parent

    # Load current app data
    with open(script_dir / 'app_data.json', 'r', encoding='utf-8') as f:
        data = json.load(f)

    # Combine all meanings
    all_meanings = {**NOUN_MEANINGS, **VERB_MEANINGS}

    # Update roots with meanings
    updated = 0
    for root in data['roots']:
        root_key = root['root']
        if not root['meaning'] and root_key in all_meanings:
            root['meaning'] = all_meanings[root_key]
            root['core_meaning'] = all_meanings[root_key].split(',')[0].strip()
            updated += 1
        elif not root['meaning']:
            # Try to find meaning from derivatives if they're verbs
            # For now, mark as needing translation
            pass

    # Count results
    with_meaning = sum(1 for r in data['roots'] if r['meaning'])
    without_meaning = sum(1 for r in data['roots'] if not r['meaning'])

    print(f"Updated {updated} roots with meanings")
    print(f"Total with meaning: {with_meaning}")
    print(f"Total without meaning: {without_meaning}")

    # Save updated data
    with open(script_dir / 'app_data.json', 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print("Saved updated app_data.json")

if __name__ == '__main__':
    main()
