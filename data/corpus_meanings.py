def convert_spaced_to_unspaced(spaced_root):
    """Convert 'ق و ل' to 'قول'"""
    return spaced_root.replace(" ", "")

def main():
    import json
    from pathlib import Path

    script_dir = Path(__file__).parent

    # Load current app data
    with open(script_dir / 'app_data.json', 'r', encoding='utf-8') as f:
        data = json.load(f)

    # Build unspaced lookup
    meanings_lookup = {}
    for spaced, meaning in CORPUS_VERBS.items():
        unspaced = convert_spaced_to_unspaced(spaced)
        meanings_lookup[unspaced] = meaning

    # Update roots
    updated = 0
    for root in data['roots']:
        root_key = root['root']
        if not root['meaning'] and root_key in meanings_lookup:
            root['meaning'] = meanings_lookup[root_key]
            root['core_meaning'] = meanings_lookup[root_key].split(',')[0].strip()
            updated += 1

    # Count results
    with_meaning = sum(1 for r in data['roots'] if r['meaning'])
    without_meaning = sum(1 for r in data['roots'] if not r['meaning'])

    print(f"Updated {updated} roots with meanings")
    print(f"Total with meaning: {with_meaning}")
    print(f"Total without meaning: {without_meaning}")

    # Save updated data
    with open(script_dir / 'app_data.json', 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print("Saved updated app_data.json")

if __name__ == '__main__':
    main()
